"""Robustness checks written during the sprint (15 Nov 2026).

    python src/robustness.py [--complete-only]   # -> report/robustness.md, report/robustness.json

(i)  MMLU vs ARC-Challenge separately; (ii) level-1-only metrics, where every condition is observed and the
stopping rule cannot matter; (iii) pooled paired win rate across models (question-level bootstrap per model,
then averaged). Uses the metric definitions in analyze.py.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from analyze import ROOT, OUT, RES, load, point_metrics, bootstrap, fmt

KEYS = ["capitulation@1", "correction@1", "decoy@1", "matched_discernment@1", "paired_win", "auroc_L1"]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--complete-only", action="store_true")
    ap.add_argument("--min-mass", type=float, default=0.5, help="same filter as analyze.py")
    a = ap.parse_args()
    data = load(RES)
    nq = sum(1 for l in (ROOT / "data" / "questions.jsonl").read_text().splitlines() if l.strip())
    if a.complete_only:
        data = {n: r for n, r in data.items() if len(r) >= nq}
    data = {n: r for n, r in data.items() if np.mean([x["mass0"] for x in r]) >= a.min_mass}
    out, lines = {}, ["# Robustness (generated by src/robustness.py)", "",
                      "Level-1 metrics by dataset. Brackets: 95% bootstrap CI over questions (1000 resamples).", "",
                      "| Model | Subset | n | n wrong | Capitulation L1 | Correction L1 | Decoy L1 | Matched discernment L1 | Paired win | AUROC L1 |",
                      "|---|---|---|---|---|---|---|---|---|---|"]
    for n, rows in data.items():
        out[n] = {}
        for sub in ("all", "mmlu", "arc"):
            S = rows if sub == "all" else [r for r in rows if r["source"] == sub]
            m = point_metrics(S); ci = bootstrap(S, KEYS)
            out[n][sub] = {k: m[k] for k in KEYS} | {"n": len(S), "n_warranted": m["n_warranted"], "ci": ci}
            lines.append(f"| {n} | {sub} | {len(S)} | {m['n_warranted']} | " + " | ".join(
                fmt(m[k], ci[k], pct=(k != "auroc_L1")) for k in KEYS) + " |")
    # pooled paired win: mean over models of per-model paired win; CI from per-model bootstrap draws
    rng = np.random.default_rng(1)
    pw = [out[n]["all"]["paired_win"] for n in out]
    draws = []
    for _ in range(1000):
        vals = []
        for n, rows in data.items():
            dec = [r for r in rows if r["condition"] == "warranted" and "decoy" in r]
            s = [dec[i] for i in rng.integers(0, len(dec), len(dec))]
            g = np.array([r["levels"][0]["p_target"] for r in s]); d = np.array([r["decoy"]["levels"][0]["p_target"] for r in s])
            vals.append(np.mean((g > d) + 0.5 * (g == d)))
        draws.append(np.mean(vals))
    pooled = {"mean_paired_win": float(np.mean(pw)), "ci": [float(np.percentile(draws, 2.5)), float(np.percentile(draws, 97.5))],
              "models": list(out)}
    out["_pooled"] = pooled
    lines += ["", f"Mean paired win rate over {len(pw)} models: {fmt(pooled['mean_paired_win'], pooled['ci'])} "
              "(bootstrap over questions within each model)."]
    (OUT / "robustness.json").write_text(json.dumps(out, indent=1))
    (OUT / "robustness.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
